#!/usr/bin/env Rscript
# =====================================================================
# Bulk-edit the front matter of publication index files.
#
# HOW TO USE
#   1. Set content_dirs to the content folders to process
#      (pre-filled: content/publications and content/talks)
#   2. Run once with dry_run <- TRUE: prints every planned change
#   3. Set dry_run <- FALSE and run again to write the files
#   4. git diff, then commit
#
# PRE-FILLED RULES
#   a) Cleanup of existing pages: delete the wowchemy comment line,
#      remove subtitle / summary / lastmod, move abstract after title.
#   b) Post-import migration for pages generated by the Python
#      `academic` CLI (academic import publications.bib ...):
#      - publication: '*Venue*'  ->  publication: {name: Venue}
#      - top-level doi           ->  hugoblox.ids.doi
#      - legacy links entries (- name / url) -> type/label/url shape
#      - delete url_pdf values pointing at local Zotero/storage paths
# =====================================================================

## ---------------- RULES ---------------------------------------------

content_dirs <- c("content/publications", "content/talks")  # folders to process
dry_run  <- FALSE                     # TRUE = only show changes, FALSE = write

## 1) Delete whole lines matching a (literal) string
delete_lines <- list(
  "# Documentation: https://wowchemy.com/docs/managing-content/",
  "Add the **full text** or **supplementary notes** for the publication here using Markdown formatting."
)

## 2) Remove front-matter fields
##    'files' matches the slug; the optional 'folders' matches the
##    content folder, e.g. "talks" = content/talks only
remove_field <- list(
  list(files = ".*", field = "subtitle"),
  list(files = ".*", field = "summary"),
  list(files = ".*", field = "lastmod"),
  list(folders = "talks", files = ".*", field = "publication_types")
)

## 3) Remove a field ONLY when its value matches a pattern
##    (used to drop url_pdf lines that point at local files)
remove_field_if <- list(
  list(files = ".*", field = "url_pdf", pattern = "Zotero/storage|file:/")
)

## 4) Move a front-matter field (with any indented continuation lines)
##    to just after another field
move_field <- list(
  list(files = ".*", field = "abstract", after = "title")
)

## 5) Legacy -> HugoBlox schema conversions for `academic import` output
nest_publication      <- TRUE   # publication: '*X*' -> name: X
move_doi_to_hugoblox  <- TRUE   # doi: ... -> hugoblox.ids.doi
convert_legacy_links  <- TRUE   # - name/url entries -> type/label/url
convert_pubtype       <- TRUE   # publication_type: '2' -> publication_types

## numeric legacy types (wowchemy/academic CLI) -> HugoBlox type names
pubtype_map <- c(
  "1" = "paper-conference",
  "2" = "article-journal",
  "3" = "manuscript",
  "4" = "report",
  "5" = "book",
  "6" = "chapter",
  "7" = "thesis",
  "8" = "patent"
)

## 6) Remove scalar fields with empty values ('' / "" / [] / {})
##    e.g. location: '', abstract: '', publication: ''
remove_empty_fields <- TRUE

## 7) Remove blogdown-era stray body: a lone 'NA' line and a
##    trailing '---' line after the front matter
clean_stray_body <- TRUE

## 8) Plain-text find & replace (applied to the whole file)
find_replace <- list(
  # c("old text", "new text")
)

## 9) Set a front-matter field (creates if missing, overwrites if present)
##    'files' matches the slug, the optional 'folders' matches the
##    content folder (e.g. "talks" = content/talks only)
set_field <- list(
  list(folders = "talks", files = ".*", field = "type", value = "event")
)

## -------------------- engine (no need to edit) ----------------------
missing <- content_dirs[!vapply(content_dirs, dir.exists, logical(1))]
if (length(missing) > 0)
  stop("These content_dirs do not exist: ", paste(missing, collapse = ", "),
       "\nRun this script from your site repo root (the folder containing 'content'),",
       "\nor use full paths, e.g. 'path/to/academic-cv/content/talks'")

n_scanned <- 0L
write_utf8 <- function(lines, path) {
  con <- file(path, open = "wb")
  writeLines(enc2utf8(lines), con = con, useBytes = TRUE)
  close(con)
}
fmt_value <- function(v) {
  if (is.character(v)) paste0("'", v, "'") else as.character(v)
}
n_changed <- 0L

## find the top-level field line(s) of `field`, including indented
## continuation lines (for multi-line values); returns row indices
find_field_block <- function(lines, field) {
  start <- grep(paste0("^", field, ":"), lines)
  if (length(start) == 0) return(integer(0))
  idx <- start
  i <- start + 1
  while (i <= length(lines) && grepl("^[[:space:]]+\\S", lines[i])) {
    idx <- c(idx, i); i <- i + 1
  }
  sort(unique(idx))
}

collapse_blanks <- function(lines) {
  keep <- logical(length(lines))
  prev_blank <- FALSE
  for (i in seq_along(lines)) {
    blank <- trimws(lines[i]) == ""
    keep[i] <- !(blank && prev_blank)
    prev_blank <- blank && keep[i]
  }
  lines[keep]
}

for (base in content_dirs) for (d in list.dirs(base, recursive = FALSE)) {
  slug <- basename(d)
  f <- file.path(d, "index.md")
  if (!file.exists(f)) next
  n_scanned <- n_scanned + 1L
  
  lines <- readLines(f, warn = FALSE, encoding = "UTF-8")
  orig <- lines
  close_idx <- which(lines == "---")[2]
  if (is.na(close_idx)) next
  
  ## ---- delete_lines ----
  for (pat in delete_lines) lines <- lines[lines != pat]
  
  ## ---- re-locate front matter bounds ----
  close_idx <- which(lines == "---")[2]
  fm_rng <- 2:(close_idx - 1)
  
  ## ---- remove_field (per slug, optionally restricted to a folder) ----
  for (rule in remove_field) {
    if (!is.null(rule$folders) && !grepl(rule$folders, base)) next
    if (!grepl(rule$files, slug)) next
    drop <- intersect(find_field_block(lines, rule$field), fm_rng)
    if (length(drop) > 0) {
      lines <- lines[-drop]
      close_idx <- which(lines == "---")[2]
      fm_rng <- 2:(close_idx - 1)
    }
  }
  
  ## ---- remove_field_if (value must match pattern) ----
  for (rule in remove_field_if) {
    if (!is.null(rule$folders) && !grepl(rule$folders, base)) next
    if (!grepl(rule$files, slug)) next
    blk <- find_field_block(lines, rule$field)
    blk <- blk[blk %in% fm_rng]
    if (length(blk) > 0 && any(grepl(rule$pattern, lines[blk]))) {
      lines <- lines[-blk]
      close_idx <- which(lines == "---")[2]
      fm_rng <- 2:(close_idx - 1)
    }
  }
  
  ## ---- move_field ----
  for (rule in move_field) {
    if (!grepl(rule$files, slug)) next
    block <- find_field_block(lines, rule$field)
    anchor <- grep(paste0("^", rule$after, ":"), lines)
    if (length(block) == 0 || length(anchor) == 0) next
    moved <- lines[block]
    lines <- lines[-block]
    ## insert after the anchor line (and its continuation lines, if any)
    ins <- max(find_field_block(lines, rule$after))
    lines <- append(lines, moved, after = ins)
    close_idx <- which(lines == "---")[2]
    fm_rng <- 2:(close_idx - 1)
  }
  
  ## ---- publication: '*Venue*'  ->  publication:\n  name: 'Venue' ----
  if (nest_publication) {
    close_idx <- which(lines == "---")[2]
    fm_rng <- 2:(close_idx - 1)
    hit <- intersect(grep("^publication: ", lines), fm_rng)
    if (length(hit) == 1 && grepl("^publication: '\\*.*\\*'$", lines[hit])) {
      inner <- sub("^publication: '\\*(.*)\\*'$", "\\1", lines[hit])
      lines[hit] <- "publication:"
      lines <- append(lines, paste0("  name: '", inner, "'"), after = hit)
    }
  }
  
  ## ---- top-level doi  ->  hugoblox.ids.doi ----
  if (move_doi_to_hugoblox) {
    close_idx <- which(lines == "---")[2]
    fm_rng <- 2:(close_idx - 1)
    blk <- find_field_block(lines, "doi")
    blk <- blk[blk %in% fm_rng]
    if (length(blk) >= 1) {
      val <- sub("^doi: *", "", lines[blk[1]])
      if (!val %in% c("''", '""', "")) {
        lines <- lines[-blk]
        close_idx <- which(lines == "---")[2]
        fm_rng <- 2:(close_idx - 1)
        hb <- intersect(grep("^hugoblox:", lines), fm_rng)
        if (length(hb) == 1) {
          ids <- intersect(grep("^  ids:", lines), fm_rng)
          if (length(ids) >= 1) {
            lines <- append(lines, paste0("    doi: ", val), after = ids[1])
          } else {
            lines <- append(lines, c("  ids:", paste0("    doi: ", val)),
                            after = hb[1])
          }
        } else {
          lines <- append(lines, c("hugoblox:", "  ids:", paste0("    doi: ", val)),
                          after = close_idx - 1)
        }
      }
    }
  }
  
  ## ---- legacy links entries: - name: X / url -> type/label/url ----
  if (convert_legacy_links) {
    close_idx <- which(lines == "---")[2]
    fm_rng <- 2:(close_idx - 1)
    lpos <- intersect(grep("^links:", lines), fm_rng)
    if (length(lpos) == 1) {
      out <- lines
      i <- lpos[1] + 1
      while (i <= length(out) && i < close_idx &&
             grepl("^(-|[[:space:]])", out[i])) {
        if (grepl("^- name: ", out[i])) {
          nm <- sub("^- name: ", "  label: ", out[i])
          out[i] <- "- type: source"
          out <- append(out, nm, after = i)
          i <- i + 1
        }
        i <- i + 1
      }
      lines <- out
    }
    ## repair files already converted with the old (buggy) rule:
    ## a "- label:" item directly after a "- type:" item belongs to
    ## the same list entry, so drop its dash
    hit <- intersect(grep("^- label: ", lines), fm_rng)
    for (h in rev(hit)) {
      if (h > 1 && grepl("^- type: ", lines[h - 1]))
        lines[h] <- sub("^- ", "  ", lines[h])
    }
  }
  
  ## ---- publication_type: 'N' -> publication_types: ["<name>"] ----
  ## ---- legacy publication type numbers -> HugoBlox type names ----
  ## handles BOTH legacy shapes:
  ##   (a) publication_type: '2'            (very old Wowchemy)
  ##   (b) publication_types:\n- '2'       (blogdown-era import)
  if (convert_pubtype) {
    close_idx <- which(lines == "---")[2]
    fm_rng <- 2:(close_idx - 1)
    
    ## (a) singular form
    hit <- intersect(grep("^publication_type:", lines), fm_rng)
    if (length(hit) >= 1) {
      num <- gsub("[^0-9]", "", lines[hit[1]])
      if (num %in% names(pubtype_map)) {
        lines[hit[1]] <- paste0('publication_types: ["', pubtype_map[[num]], '"]')
        if (length(hit) > 1) lines <- lines[-hit[-1]]
      } else if (num == "0") {
        lines <- lines[-hit]   # legacy '0' = uncategorized -> drop the field
      } else {
        warning(slug, ": unknown publication_type '", lines[hit[1]], "' - left unchanged")
      }
    }
    
    ## (b) plural list form holding bare numbers, e.g.
    ##     publication_types:
    ##     - '7'
    close_idx <- which(lines == "---")[2]
    fm_rng <- 2:(close_idx - 1)
    hit2 <- intersect(grep("^publication_types: *$", lines), fm_rng)
    if (length(hit2) == 1) {
      j <- hit2[1] + 1
      nums <- character(0)
      while (j <= length(lines) && j < close_idx && grepl("^- ", lines[j]) &&
             grepl("[0-9]", lines[j]) && !grepl("[A-Za-z]", lines[j])) {
        nums <- c(nums, gsub("[^0-9]", "", lines[j])); j <- j + 1
      }
      if (length(nums) >= 1) {
        mapped <- pubtype_map[nums]
        if (all(!is.na(mapped))) {
          lines[hit2[1]] <- paste0('publication_types: ["',
                                   paste(mapped, collapse = '", "'), '"]')
          lines <- lines[-((hit2[1] + 1):(hit2[1] + length(nums)))]
        } else if (all(nums == "0")) {
          lines <- lines[-(hit2[1]:(hit2[1] + length(nums)))]  # uncategorized -> drop
        } else {
          warning(slug, ": unknown publication_types number(s) '",
                  paste(nums, collapse = "', '"), "' - left unchanged")
        }
      }
    }
  }
  
  ## ---- remove scalar fields with empty values ----
  if (remove_empty_fields) {
    close_idx <- which(lines == "---")[2]
    fm_rng <- 2:(close_idx - 1)
    drop <- integer(0)
    ## (also covers indented single-line empties, e.g. "    doi: ''"
    ##  inside a hugoblox.ids block)
    for (i in fm_rng) {
      if (grepl("^[[:space:]]*[A-Za-z_][A-Za-z0-9_-]*: *(''|\"\"|\\[\\]|\\{\\}) *$",
                lines[i]))
        drop <- c(drop, i)
    }
    if (length(drop) > 0) {
      lines <- lines[-drop]
      close_idx <- which(lines == "---")[2]
      fm_rng <- 2:(close_idx - 1)
    }
  }
  
  ## ---- find_replace (whole file) ----
  if (length(find_replace) > 0) {
    for (i in seq_along(lines)) {
      for (pair in find_replace) {
        lines[i] <- gsub(pair[1], pair[2], lines[i], fixed = TRUE)
      }
    }
  }
  
  ## ---- set_field (per slug, optionally restricted to a folder) ----
  for (rule in set_field) {
    if (!is.null(rule$folders) && !grepl(rule$folders, base)) next
    if (!grepl(rule$files, slug)) next
    close_idx <- which(lines == "---")[2]
    hit <- grep(paste0("^", rule$field, ":"), lines[2:(close_idx - 1)])
    if (length(hit) > 0) {
      lines[hit[1] + 1] <- paste0(rule$field, ": ", fmt_value(rule$value))
    } else {
      lines <- append(lines, paste0(rule$field, ": ", fmt_value(rule$value)),
                      after = close_idx - 1)
    }
  }
  
  ## ---- clean stray blogdown body: lone 'NA' + trailing '---' ----
  if (clean_stray_body) {
    close_idx <- which(lines == "---")[2]
    if (!is.na(close_idx) && close_idx < length(lines)) {
      body <- (close_idx + 1):length(lines)
      drop <- body[trimws(lines[body]) == "NA"]
      if (length(drop) > 0) lines <- lines[-drop]
      ## trailing '---' after the front matter (only if it is the last line)
      last <- length(lines)
      while (last > close_idx && trimws(lines[last]) == "") last <- last - 1
      if (last > close_idx && trimws(lines[last]) == "---") lines <- lines[-last]
    }
  }
  
  ## ---- tidy up leftover blank runs ----
  lines <- collapse_blanks(lines)
  
  if (!identical(lines, orig)) {
    n_changed <- n_changed + 1L
    if (dry_run) {
      message("WOULD CHANGE: ", slug)
      changed <- which(lines != orig)
      for (i in changed) {
        old <- if (i <= length(orig)) orig[i] else "<new line>"
        message("    - ", old, "\n    + ", lines[i])
      }
    } else {
      write_utf8(lines, f)
      message("CHANGED: ", slug)
    }
  }
}

message("\n", if (dry_run) "Dry run - " else "",
        n_changed, " of ", n_scanned, " file(s) ",
        if (dry_run) "would be " else "", "modified.")
if (n_scanned == 0)
  warning("No index.md files found under ", pubs_dir,
          " - check the path and the working directory (getwd()).")